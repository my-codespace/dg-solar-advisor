// ── Step 4: Shareable Report ──────────────────────────────────────────────────

import React, { useRef } from 'react';
import { Share2, Printer, Copy, CheckCircle2, ExternalLink } from 'lucide-react';
import { useT, fmtCr, fmt } from '../i18n';
import { Banner } from '../components/UI';
import type { AnalysisResponse, Lang } from '../types';

interface Props {
  lang: Lang;
  results: AnalysisResponse;
  reportId: string | null;
  summaryEn?: string;
  summaryHi?: string;
  onBack: () => void;
  onNewAnalysis: () => void;
}

export function ReportStep({ lang, results, reportId, summaryEn, summaryHi, onBack, onNewAnalysis }: Props) {
  const t = useT(lang);
  const reportRef = useRef<HTMLDivElement>(null);
  const [copied, setCopied] = React.useState(false);

  const reportUrl = reportId
    ? `${window.location.origin}/?report=${reportId}`
    : null;

  function handleCopy() {
    if (reportUrl) {
      navigator.clipboard.writeText(reportUrl);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    }
  }

  function handlePrint() {
    window.print();
  }

  const reportData = (results as any)?.results ?? results ?? {};
  const dg = reportData.dg ?? (results as any)?.dg ?? {};
  const financials = reportData.financials ?? (results as any)?.financials ?? {};
  const solar = reportData.solar ?? (results as any)?.solar ?? {};
  const battery = reportData.battery ?? (results as any)?.battery ?? {};
  const societyName = reportData.societyName || (results as any)?.societyName || 'Housing Society';
  const city = reportData.city || (results as any)?.city || '';

  return (
    <div className="animate-fade-in space-y-8">
      {/* Header */}
      <div className="flex items-center justify-between flex-wrap gap-4">
        <div>
          <h2 className="text-2xl font-bold text-white">{t('step4')}</h2>
          <p className="text-slate-400 text-sm">{societyName} — {city}</p>
        </div>
        <div className="flex gap-3 no-print">
          {reportUrl && (
            <button onClick={handleCopy} className="btn-secondary flex items-center gap-2 text-sm">
              {copied ? <CheckCircle2 size={15} className="text-emerald-400" /> : <Copy size={15} />}
              {copied ? 'Copied!' : 'Copy Link'}
            </button>
          )}
          <button onClick={handlePrint} className="btn-secondary flex items-center gap-2 text-sm">
            <Printer size={15} /> {t('printReport')}
          </button>
        </div>
      </div>

      {/* Share link */}
      {reportUrl && (
        <div className="glass p-4 flex items-center gap-3">
          <Share2 size={18} className="text-solar-400 shrink-0" />
          <div className="flex-1 min-w-0">
            <p className="text-xs text-slate-400 mb-1">{t('reportUrl')}</p>
            <p className="text-sm text-solar-300 truncate font-mono">{reportUrl}</p>
          </div>
          <button onClick={handleCopy} className="btn-ghost text-sm shrink-0">
            {copied ? '✓' : 'Copy'}
          </button>
        </div>
      )}
      {!reportId && (
        <Banner variant="info">
          Report not saved to cloud (API unavailable). Use Print / PDF to save a copy.
        </Banner>
      )}

      {/* ── Printable Report ─────────────────────────────────────────────────── */}
      <div ref={reportRef} className="space-y-8 print:space-y-6">

        {/* Title block */}
        <div className="glass p-8 text-center glow-solar">
          <div className="text-4xl mb-3">☀️</div>
          <h1 className="text-3xl font-bold text-gradient mb-2">SunSwitch Solar Advisory Report</h1>
          <p className="text-slate-300 text-lg">{societyName}</p>
          <p className="text-slate-500 text-sm">{city} · {new Date().toLocaleDateString('en-IN', { year: 'numeric', month: 'long', day: 'numeric' })}</p>
          <p className="text-xs text-slate-600 mt-2">Generated by SunSwitch · Environmental Hacks x AWS Hackathon Project</p>
        </div>

        {/* Plain-language summary (AI or template) */}
        {(summaryEn || (results as any)?.summaryEn) && (
          <div className="glass p-6 space-y-4">
            <h2 className="text-lg font-bold text-white border-b border-white/10 pb-3">{t('summaryEn')}</h2>
            <p className="text-slate-300 leading-relaxed whitespace-pre-line text-sm">
              {summaryEn || (results as any)?.summaryEn}
            </p>
          </div>
        )}

        {(summaryHi || (results as any)?.summaryHi) && (
          <div className="glass p-6 space-y-4" style={{ fontFamily: "'Noto Sans Devanagari', sans-serif" }}>
            <h2 className="text-lg font-bold text-white border-b border-white/10 pb-3">{t('summaryHi')}</h2>
            <p className="text-slate-300 leading-relaxed whitespace-pre-line text-sm">
              {summaryHi || (results as any)?.summaryHi}
            </p>
          </div>
        )}

        {/* Key numbers table */}
        <div className="glass p-6">
          <h2 className="text-lg font-bold text-white mb-5 border-b border-white/10 pb-3">Key Numbers at a Glance</h2>
          <table className="w-full text-sm">
            <tbody className="divide-y divide-white/5">
              {[
                ['DG Cost per kWh', `₹${dg?.cost_per_kwh_rs ?? 0}`, 'red'],
                ['Grid Tariff', `₹${financials?.grid_cost_per_kwh_rs ?? 0}/kWh`, 'orange'],
                ['Solar LCOE', `₹${financials?.solar_lcoe_rs_per_kwh ?? 0}/kWh`, 'green'],
                ['Annual DG Spend', fmtCr(dg?.annual_cost_rs ?? 0), 'red'],
                ['Annual DG CO₂', `${fmt(dg?.co2_kg ?? 0)} kg`, 'red'],
                ['Solar Capacity', `${fmt(financials?.solar_capacity_kw ?? 0, 1)} kWp`, 'yellow'],
                ['Year-1 Solar Generation', `${fmt(solar?.year1_kwh ?? 0)} kWh`, 'yellow'],
                ['Gross Installation Cost', fmtCr(financials?.gross_installation_cost_rs ?? 0), ''],
                ['PM Surya Ghar Subsidy', `− ${fmtCr(financials?.subsidy_amount_rs ?? 0)}`, 'green'],
                ['Net Cost (after subsidy)', fmtCr(financials?.net_installation_cost_rs ?? 0), 'yellow'],
                ['Payback Period', `${financials?.payback_years ?? 0} years`, 'green'],
                ['25-Year NPV', fmtCr(financials?.npv_rs ?? 0), 'green'],
                ['25-Year Savings', fmtCr(financials?.year25_savings_rs ?? 0), 'green'],
                ['CO₂ Avoided (25 yr)', `${fmt(financials?.co2_avoided_25yr_tonnes ?? 0)} tonnes`, 'green'],
                ['Battery Backup', `${fmt(battery?.required_capacity_kwh ?? 0, 0)} kWh`, ''],
              ].map(([label, value, color]) => (
                <tr key={label as string}>
                  <td className="py-2.5 text-slate-400 pr-4">{label}</td>
                  <td className={`py-2.5 font-semibold text-right ${
                    color === 'red' ? 'text-red-300' :
                    color === 'green' ? 'text-emerald-300' :
                    color === 'yellow' ? 'text-solar-300' :
                    color === 'orange' ? 'text-orange-300' : 'text-white'
                  }`}>{value}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>

        {/* Subsidy note */}
        <div className="glass p-4 text-sm">
          <p className="text-amber-200 flex items-start gap-2">
            ⚠️ {financials.subsidy_note}{' '}
            <a href="https://pmsuryaghar.gov.in" target="_blank" rel="noopener noreferrer" className="underline inline-flex items-center gap-0.5 ml-1">
              pmsuryaghar.gov.in <ExternalLink size={11} />
            </a>
          </p>
        </div>

        {/* Disclaimer */}
        <div className="glass p-4 border border-amber-500/20">
          <p className="text-xs text-slate-500">{results.disclaimer}</p>
          <p className="text-xs text-slate-600 mt-1">{t('noPrivacy')}</p>
        </div>
      </div>

      {/* Nav */}
      <div className="flex justify-between no-print flex-wrap gap-3">
        <button id="report-back-btn" className="btn-secondary" onClick={onBack}>{t('back')}</button>
        <button id="new-analysis-btn" className="btn-primary" onClick={onNewAnalysis}>Start New Analysis</button>
      </div>
    </div>
  );
}
